import { fixtures, ownerLogin, trackBrowserErrors, noPageOverflow } from './helpers';

test('Kasir categories combine with search and leave salon services unchanged', async ({ page }) => {
  const errors = trackBrowserErrors(page);
  await ownerLogin(page);
  const filters = page.getByRole('group', { name: 'Saring produk menurut kategori', exact: true });
  await filters.getByRole('button', { name: 'Makanan', exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(2);
  const food = filters.getByRole('button', { name: 'Makanan', exact: true });
  await food.hover();
  const selectedStyle = await food.evaluate(element => ({ color: getComputedStyle(element).color, background: getComputedStyle(element).backgroundColor }));
  expect(selectedStyle.color).toBe('rgb(255, 255, 255)');
  expect(selectedStyle.background).toBe('rgb(113, 48, 64)');
  await page.getByLabel('Cari produk', { exact: true }).fill('Produk kasir');
  await expect(page.locator('.catalog-item')).toHaveCount(1);
  await expect(page.getByRole('button', { name: /Tambah.*Produk kasir ke pesanan/ })).toBeVisible();
  await filters.getByRole('button', { name: 'Snack', exact: true }).click();
  await expect(page.getByText('Tidak ada produk kategori Snack yang cocok dengan pencarian ini.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Hapus pencarian', exact: true }).first().click();
  await expect(page.locator('.catalog-item')).toHaveCount(1);
  await expect(page.getByRole('button', { name: /Tambah.*Produk dengan nama panjang/ })).toBeVisible();
  await filters.getByRole('button', { name: 'Minuman', exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(18);
  await filters.getByRole('button', { name: 'Tanpa kategori', exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(1);
  await expect(page.getByRole('button', { name: /Tambah.*Produk tanpa kategori/ })).toBeVisible();
  await filters.getByRole('button', { name: 'Semua', exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(20);
  await page.getByLabel('Unit usaha', { exact: true }).selectOption(fixtures.salon.id);
  await expect(page.getByRole('button', { name: /Tambah.*Layanan salon/ })).toBeVisible();
  await expect(page.getByRole('group', { name: 'Saring produk menurut kategori', exact: true })).toHaveCount(0);
  await noPageOverflow(page);
  expect(errors).toEqual([]);
});

test('Katalog creates, renames, assigns, archives and restores real categories', async ({ page }) => {
  const errors = trackBrowserErrors(page);
  await ownerLogin(page);
  await page.getByRole('link', { name: 'Katalog', exact: true }).click();
  const panel = page.getByRole('region', { name: 'Kategori', exact: true });
  const products = page.getByRole('region', { name: 'Kategori produk', exact: true });
  const name = `[UJI E2E] Baru ${randomUUID()}`;
  await page.getByLabel('Nama kategori baru', { exact: true }).fill(name);
  const createdPromise = page.waitForResponse(response => response.url().includes('/api/pos/categories?') && response.request().method() === 'POST');
  await page.getByRole('button', { name: 'Tambah kategori', exact: true }).click();
  const category = await (await createdPromise).json();
  await expect(panel.getByText(name, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: `Ubah nama kategori ${name}`, exact: true }).click();
  const renamed = `${name} Baru`;
  await page.getByLabel('Nama kategori', { exact: true }).fill(renamed);
  await page.getByRole('button', { name: 'Simpan nama', exact: true }).click();
  await expect(panel.getByText(renamed, { exact: true })).toBeVisible();
  await products.getByLabel('Cari produk', { exact: true }).fill('Produk kasir');
  const select = page.getByLabel(`Kategori ${fixtures.product.name}`, { exact: true });
  await select.selectOption(category.id);
  const assignmentPromise = page.waitForResponse(response => response.url().endsWith(`/api/pos/products/${fixtures.product.id}`) && response.request().method() === 'PATCH');
  await page.getByRole('button', { name: `Simpan kategori ${fixtures.product.name}`, exact: true }).click();
  const assigned = await (await assignmentPromise).json();
  expect(assigned.categoryId).toBe(category.id);
  expect(assigned.price).toBe(fixtures.product.price);
  await expect(select).toHaveValue(category.id);
  await page.getByRole('link', { name: 'Kasir', exact: true }).click();
  const filter = page.getByRole('group', { name: 'Saring produk menurut kategori', exact: true });
  await filter.getByRole('button', { name: renamed, exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(1);
  await expect(page.getByRole('button', { name: /Tambah.*Produk kasir/ })).toBeVisible();
  await page.getByRole('link', { name: 'Katalog', exact: true }).click();
  await page.getByRole('button', { name: `Arsipkan kategori ${renamed}`, exact: true }).click();
  let dialog = page.getByRole('dialog', { name: `Arsipkan kategori ${renamed}?`, exact: true });
  const refusedPromise = page.waitForResponse(response => response.url().endsWith(`/api/pos/categories/${category.id}`) && response.request().method() === 'DELETE');
  await dialog.getByRole('button', { name: 'Arsipkan', exact: true }).click();
  expect((await refusedPromise).status()).toBe(409);
  await expect(dialog.getByRole('alert')).toBeVisible();
  await dialog.getByRole('button', { name: 'Batal', exact: true }).click();
  await products.getByLabel('Cari produk', { exact: true }).fill('Produk kasir');
  await page.getByRole('button', { name: `Hapus kategori dari ${fixtures.product.name}`, exact: true }).click();
  await expect(select).toHaveValue('');
  await page.getByRole('button', { name: `Arsipkan kategori ${renamed}`, exact: true }).click();
  dialog = page.getByRole('dialog', { name: `Arsipkan kategori ${renamed}?`, exact: true });
  await dialog.getByRole('button', { name: 'Arsipkan', exact: true }).click();
  await expect(dialog).toBeHidden();
  const status = page.getByRole('group', { name: 'Saring kategori menurut status', exact: true });
  await status.getByRole('button', { name: 'Diarsipkan', exact: true }).click();
  await expect(panel.getByText(renamed, { exact: true })).toBeVisible();
  await page.getByRole('button', { name: `Pulihkan kategori ${renamed}`, exact: true }).click();
  await status.getByRole('button', { name: 'Aktif', exact: true }).click();
  await expect(panel.getByText(renamed, { exact: true })).toBeVisible();
  // Leave fixture associations as they were, without changing price or stock.
  await products.getByLabel('Cari produk', { exact: true }).fill('Produk kasir');
  await select.selectOption(fixtures.categories.makanan.id);
  await page.getByRole('button', { name: `Simpan kategori ${fixtures.product.name}`, exact: true }).click();
  await expect(select).toHaveValue(fixtures.categories.makanan.id);
  await noPageOverflow(page);
  await page.screenshot({ path: 'test-results/katalog-categories.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('cashier uses category filters but cannot open category administration', async ({ page }) => {
  const errors = trackBrowserErrors(page);
  await page.goto('/login');
  await page.getByLabel('Email', { exact: true }).fill(fixtures.cashier.email);
  await page.getByLabel('Kata sandi', { exact: true }).fill(fixtures.cashier.password);
  await page.getByRole('button', { name: 'Masuk', exact: true }).click();
  await expect(page).toHaveURL(/\/kasir/);
  await expect(page.getByRole('link', { name: 'Katalog', exact: true })).toHaveCount(0);
  await page.getByRole('group', { name: 'Saring produk menurut kategori', exact: true }).getByRole('button', { name: 'Minuman', exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(18);
  await page.goto('/katalog');
  await expect(page.getByText(/Pengaturan katalog hanya dapat dibuka oleh pemilik dan admin/)).toBeVisible();
  await expect(page.getByLabel('Nama kategori baru', { exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('category read errors preserve usable all/unassigned filters without fake category data', async ({ page }) => {
  const errors = trackBrowserErrors(page);
  await page.route('**/api/pos/categories?**', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: { code: 'UPSTREAM_UNAVAILABLE', message: '[UJI E2E] kategori tidak tersedia' } }) }));
  await ownerLogin(page);
  await expect(page.getByText('Daftar kategori belum dapat dimuat.', { exact: true })).toBeVisible();
  const filters = page.getByRole('group', { name: 'Saring produk menurut kategori', exact: true });
  await filters.getByRole('button', { name: 'Tanpa kategori', exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(1);
  await filters.getByRole('button', { name: 'Semua', exact: true }).click();
  await expect(page.locator('.catalog-item')).toHaveCount(20);
  await page.unroute('**/api/pos/categories?**');
  await page.getByRole('button', { name: 'Coba lagi', exact: true }).click();
  await expect(filters.getByRole('button', { name: 'Makanan', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
